#!/usr/bin/env python3
"""Prepare per-abnormality-type datasets for research-grade analysis.

Problem this solves
- Some pre-made datasets can end up with *no abnormal rows* for a given split
  (e.g. route_switch has only normal rows in train), which breaks per-type
  comparisons.

What this tool does
- Starting from an input dataset directory (e.g. data/Beijing), create one
  output dataset directory per abnormality type.
- Each output dataset contains:
  - train/val/test CSVs generated by the existing streaming generator in
    `generate_hoser_abnormalities.py`, but restricted to a *single* type.
  - Symlinks (or copies) of non-CSV dataset assets (roadmap.geo, roadmap.rel,
    road_network_partition/, zone_trans_mat.npy, etc.) so evaluation tools can
    run against the output directory directly.
- Writes a small manifest JSON per output dataset with counts per split.

This produces datasets suitable for:
- `tools/evaluate_dataset_with_lmtad.py`
- `tools/run_lmtad_decision_benchmark.py` (use --target-data-dirs)

Example
uv run python tools/prepare_per_type_abnormal_datasets.py \
  --input-dir data/Beijing \
  --out-root data/_per_type \
  --types detour,route_switch,perturb \
  --abnormality-rate 0.05 \
  --level medium \
  --seed 42 \
  --ensure-change \
  --strong-prob 0.3
"""

from __future__ import annotations

import argparse
import csv
import json
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Tuple


# Make repo root importable when executed as `python tools/...py`
_REPO_ROOT = Path(__file__).resolve().parents[1]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))


_NULL_LIKE = {"", "nan", "none", "null"}


def _is_abnormal(raw: str) -> bool:
    s = str(raw or "").strip().lower()
    if s in _NULL_LIKE or s == "normal":
        return False
    return True


def _safe_symlink_or_copy(src: Path, dst: Path) -> None:
    """Symlink src->dst, falling back to copy on failure."""
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists() or dst.is_symlink():
        return

    try:
        # Prefer symlink for speed and disk usage.
        dst.symlink_to(src)
        return
    except Exception:
        pass

    if src.is_dir():
        shutil.copytree(src, dst)
    else:
        shutil.copy2(src, dst)


def _link_assets(input_dir: Path, out_dir: Path) -> None:
    """Link/copy required dataset assets from input_dir into out_dir.

    We intentionally *do not* mirror every file in the dataset directory.
    Some datasets contain large evaluation folders or caches (e.g. eval_*/,
    gene_preprocessed_cache.pkl) which are not needed for evaluation and could
    be expensive to copy if symlinks are unavailable.
    """
    out_dir.mkdir(parents=True, exist_ok=True)

    # Minimal set of assets required by evaluation / generation utilities.
    allowlist = {
        "roadmap.geo",
        "roadmap.rel",
        "road_network_partition",
        "zone_trans_mat.npy",
        "README.md",
    }

    for name in sorted(allowlist):
        src = input_dir / name
        if src.exists():
            _safe_symlink_or_copy(src, out_dir / name)


def _count_split(csv_path: Path) -> Tuple[int, int]:
    """Return (rows_total, rows_abnormal) for a split CSV."""
    if not csv_path.exists():
        return 0, 0

    total = 0
    abn = 0
    with csv_path.open("r", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            total += 1
            if _is_abnormal(row.get("abnormality_info", "")):
                abn += 1
    return total, abn


@dataclass(frozen=True)
class DatasetManifest:
    input_dir: str
    output_dir: str
    abnormality_type: str
    abnormality_rate: float
    level: str
    seed: int
    ensure_change: bool
    strong_prob: float
    splits: List[str]
    counts: Dict[str, Dict[str, int]]


def _write_manifest(path: Path, manifest: DatasetManifest) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(manifest.__dict__, indent=2, sort_keys=True) + "\n")


def _parse_types(raw: str) -> List[str]:
    parts = [p.strip() for p in str(raw).split(",") if p.strip()]
    if not parts:
        raise ValueError("No types provided")
    return parts


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Create per-abnormality-type datasets (detour-only, route_switch-only, etc.)"
    )
    parser.add_argument("--input-dir", type=Path, required=True)
    parser.add_argument(
        "--out-root",
        type=Path,
        required=True,
        help="Directory under which per-type dataset dirs are created.",
    )
    parser.add_argument(
        "--types",
        type=str,
        default="detour,route_switch,perturb",
        help="Comma-separated abnormality types to generate.",
    )
    parser.add_argument("--splits", type=str, default="train,val,test")
    parser.add_argument(
        "--abnormality-rate",
        type=float,
        default=0.05,
        help="Probability per input row of generating an abnormal row for this type.",
    )
    parser.add_argument("--level", type=str, default="medium")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--ensure-change", action="store_true")
    parser.add_argument(
        "--strong-prob",
        type=float,
        default=0.3,
        help="Probability that generated anomalies use 'strong' mode.",
    )
    parser.add_argument(
        "--name-suffix",
        type=str,
        default="per_type",
        help="Suffix appended to output dir names.",
    )

    args = parser.parse_args()

    input_dir = Path(args.input_dir)
    if not input_dir.exists():
        raise FileNotFoundError(f"Input dataset dir not found: {input_dir}")

    out_root = Path(args.out_root)
    out_root.mkdir(parents=True, exist_ok=True)

    types = _parse_types(args.types)
    splits = [s.strip() for s in str(args.splits).split(",") if s.strip()]
    if not splits:
        raise ValueError("No splits provided")

    # Import generator functions from the existing script.
    # (We intentionally call the internal streaming function for determinism
    #  and to avoid subprocess / shell quoting issues.)
    import generate_hoser_abnormalities as gen

    for ab_type in types:
        out_dir = out_root / f"{input_dir.name}_{args.name_suffix}_{ab_type}"
        out_dir.mkdir(parents=True, exist_ok=True)

        # Ensure evaluation assets exist in output dir.
        _link_assets(input_dir, out_dir)

        # Generate split CSVs.
        for split in splits:
            in_csv = input_dir / f"{split}.csv"
            if not in_csv.exists():
                # Skip missing split.
                continue
            out_csv = out_dir / f"{split}.csv"

            # Generate only this type.
            gen.process_split_streaming(
                input_path=str(in_csv),
                output_path=str(out_csv),
                seed=int(args.seed),
                level=str(args.level),
                abnormal_types=[str(ab_type)],
                abnormality_rate=float(args.abnormality_rate),
                abnormality_weights=[1.0],
                ensure_change=bool(args.ensure_change),
                progress_interval=10000,
                strong_prob=float(args.strong_prob),
            )

        # Manifest with counts.
        counts: Dict[str, Dict[str, int]] = {}
        for split in splits:
            total, abn = _count_split(out_dir / f"{split}.csv")
            counts[split] = {"rows": int(total), "abnormal_rows": int(abn)}

        manifest = DatasetManifest(
            input_dir=str(input_dir),
            output_dir=str(out_dir),
            abnormality_type=str(ab_type),
            abnormality_rate=float(args.abnormality_rate),
            level=str(args.level),
            seed=int(args.seed),
            ensure_change=bool(args.ensure_change),
            strong_prob=float(args.strong_prob),
            splits=list(splits),
            counts=counts,
        )
        _write_manifest(out_dir / "per_type_manifest.json", manifest)

        print(str(out_dir))

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
